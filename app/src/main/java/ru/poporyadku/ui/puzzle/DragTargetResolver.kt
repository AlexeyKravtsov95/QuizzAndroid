package ru.poporyadku.ui.puzzle

/**
 * Единственный порог перестановки при перетаскивании (ITERATION_6_DESIGN.md, §5.3,
 * I6-D7).
 *
 * Чистая функция без платформы и без Compose: геометрия приходит числами в px, поэтому
 * порог проверяется JVM-тестом `I6-R3` без экрана и без эмулятора.
 *
 * **Правило одно:** перетаскиваемая карточка переходит через соседнюю тогда и только
 * тогда, когда её визуальный центр **строго** пересекает центр этой соседней карточки.
 * Попадание центра в границы карточки и любое фиксированное расстояние в dp не
 * используются: у карточек разная высота, и «половина шага списка» на них не определена.
 */
object DragTargetResolver {

    /**
     * @param i текущий подтверждённый индекс перетаскиваемой карточки.
     * @param lastIndex индекс последней карточки; результат ограничен `0..lastIndex`.
     * @param draggedCenter визуальный центр перетаскиваемой карточки:
     * `slotTop(i) + offsetY + height(i) / 2`.
     * @param centerOf центр карточки, стоящей на подтверждённом индексе `k`, в текущей
     * раскладке; `null` — карточка не видна, её центр неизвестен.
     *
     * @return индекс, на который карточку следует поставить. Равен [i], если порог не
     * пересечён: равенство центров перестановки не даёт.
     *
     * За один вызов может быть пройдено несколько соседей: быстрый жест, пересёкший два
     * центра между сэмплами, даёт одну цель, одну перестановку и одну отдачу, а не две.
     */
    fun targetIndex(
        i: Int,
        lastIndex: Int,
        draggedCenter: Float,
        centerOf: (Int) -> Float?,
    ): Int {
        var target = i

        // Вниз: пока центр строго ниже центра следующего соседа.
        while (target < lastIndex) {
            // Невидимый сосед — стоп до следующего кадра: его центр неизвестен, и
            // «перепрыгнуть» через него по догадке нельзя. Auto-scroll сделает его
            // видимым, и порог проверится в следующем кадре.
            val center = centerOf(target + 1) ?: break
            if (draggedCenter > center) target++ else break
        }
        if (target != i) return target

        // Вверх: симметрично. Проверяется только если вниз не сдвинулись ни на шаг —
        // одновременно обе стороны недостижимы.
        while (target > 0) {
            val center = centerOf(target - 1) ?: break
            if (draggedCenter < center) target-- else break
        }
        return target
    }
}
