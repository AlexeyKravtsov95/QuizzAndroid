package ru.poporyadku.ui.feedback

/**
 * Что именно подтверждает отдача (ITERATION_5_DESIGN.md, §3.14, §4.7, I5-D22;
 * ITERATION_6_DESIGN.md, §6, I6-D14).
 *
 * Ровно три повода: захват карточки, перестановка карточки и принятый ответ. Ни «ошибка»,
 * ни «начало дня», ни «победа» — `DESIGN_PRINCIPLES.md` §9 запрещает победные звуки, и
 * отдача здесь сообщает о факте, а не хвалит.
 */
enum class FeedbackCue {

    /**
     * Карточку взяли за ручку: ViewModel принял начало нового жеста в `Playing`.
     *
     * **Только тактильно, звука нет никогда** (I6-D14): захват фактом порядка не
     * является, а щелчок захвата сразу перед щелчком перемещения звучал бы как двойной
     * отклик на одно действие.
     */
    CardGrabbed,

    /** Порядок карточек фактически изменился. */
    CardMoved,

    /** Попытка записана как ответ — уже в базе, а не «отправляется». */
    AnswerAccepted,
}
