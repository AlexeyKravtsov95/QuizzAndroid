package ru.poporyadku.domain.reminder

/**
 * Показ и снятие напоминания (ITERATION_6_DESIGN.md, §9.1, §10.1, I6-D24, I6-D34).
 *
 * Доменная граница: системный менеджер уведомлений и его типы в `domain` не
 * упоминаются. Единственная реализация — `notifications/AndroidReminderNotifier`.
 */
interface ReminderNotifier {

    /**
     * Показать напоминание. Реализация перед показом **ещё раз** проверяет доступ
     * (разрешение могли отозвать между оценкой и показом) и не выпускает наружу отказ
     * платформы.
     */
    suspend fun show()

    /** Снять показанное напоминание, если оно есть. Идемпотентно. */
    fun cancelShown()
}
