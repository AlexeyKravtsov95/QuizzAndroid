package ru.poporyadku.domain.content

/**
 * Установка пакета контента, встроенного в приложение (ITERATION_3_DESIGN.md, I3-D2,
 * I3-D41; ITERATION_4_DESIGN.md, §10).
 *
 * Вызывается use case'ами перед любым обращением к наборам и головоломкам. «Установлено ли»
 * решает содержимое базы, а не флаг в процессе: полная очистка базы отладочным инструментом
 * в том же процессе обязана приводить к переустановке.
 */
interface ContentInstaller {

    /**
     * Идемпотентно приводит базу к встроенному пакету.
     *
     * Ранний выход без единой записи разрешён, только когда состояние согласовано ПОЛНОСТЬЮ
     * (**I4-D11**): версия и отпечаток пакета совпали с отметкой об установке, И база это
     * подтверждает — строки наборов пакета равны ожидаемым, назначений вне диапазона пакета
     * нет, сыгранные головоломки не расходятся со своими слотами недопустимым образом,
     * а головоломки наборов на месте, текущей версии и активны. Одной отметки недостаточно;
     * при любом «нет» пакет импортируется заново, и повтор после отказа безопасен.
     *
     * Импорт сохраняет прогресс: назначения, попытки и итоги дней не удаляются и не
     * изменяются, головоломки не удаляются никогда — отозванная остаётся доступной архиву.
     *
     * Атомарная граница — **I4-D13**: вся запись контента выполняется одной транзакцией Room,
     * а отметка об установке пишется только после её commit, никогда раньше.
     *
     * @throws ContentInstallException.Conflict если пакет небезопасно расходится с локальной
     * историей: назначение вне диапазона пакета, изменившийся состав назначенного набора или
     * сыгранная головоломка, чужая своему слоту (допустима лишь послотовая замена отозванной,
     * **I4-D4**). Ни одна таблица и отметка об установке при этом не изменены.
     * @throws ContentInstallException.BundleInvalid если встроенный пакет не соответствует
     * контракту.
     * @throws ContentInstallException.UnsupportedSchema если формат пакета новее, чем
     * понимает приложение.
     * @throws ContentInstallException.AssetUnreadable если файл пакета не прочитался.
     */
    suspend fun ensureInstalled()
}
