package ru.poporyadku.domain.content

/**
 * Установка активного контента (ITERATION_3_DESIGN.md, I3-D2, I3-D41).
 *
 * Вызывается use case'ами перед любым обращением к наборам. «Установлено ли» решает
 * содержимое базы, а не флаг в процессе: полная очистка базы отладочным инструментом
 * в том же процессе обязана приводить к переустановке.
 */
interface ContentInstaller {

    /**
     * Идемпотентно: при точном составе наборов не выполняет ни одной записи.
     *
     * @throws ContentInstallException.Conflict если остаточные наборы заняты
     * назначениями — авто-очистка стёрла бы прогресс пользователя.
     */
    suspend fun ensureInstalled()
}
