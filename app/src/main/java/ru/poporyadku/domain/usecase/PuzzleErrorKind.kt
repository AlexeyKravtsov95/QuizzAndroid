package ru.poporyadku.domain.usecase

/**
 * Вид отказа игрового потока (ITERATION_3_DESIGN.md, §8, раздел 18).
 *
 * Доменный тип, а не текст: ни одной строки для пользователя из `domain` не выходит.
 * Соответствие «вид ошибки → строка ресурса» живёт в `ui`.
 */
enum class PuzzleErrorKind {
    /**
     * Аргументы маршрута не разбираются: `date` отсутствует или не является ISO-датой,
     * `slotIndex` отсутствует или вне диапазона (I3-D39).
     *
     * Живёт здесь, а не в `ui`: экранные состояния обоих игровых экранов уже описаны
     * через этот перечень, и UI-дубликат доменного значения развёл бы два списка видов
     * отказа, которые обязаны совпадать.
     */
    InvalidRoute,

    /** `slotIndex` вне 0..2 — пришёл из маршрута или из восстановленного состояния. */
    SlotOutOfRange,

    /** На эту дату набор не выдавался. */
    NoAssignment,

    /** Назначение есть, а набора под него нет — дефект контента. */
    SetNotFound,

    /** Головоломки с таким `puzzleId` нет в активном контенте. */
    PuzzleNotFound,

    /** Головоломка не проходит проверку формы (`isPlayable`). */
    InvalidPuzzle,

    /** Сбой хранилища. */
    Storage,
}
